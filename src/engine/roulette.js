/**
 * Правила кино-рулетки.
 *
 * Рулетка снимает с человека необходимость выбирать. Но случайность
 * из всего каталога — это лотерея, где чаще всего выпадает то, что
 * смотреть не станут. Поэтому барабан набирается не из чего попало,
 * а из близкого вкусу — и уже внутри отобранного жребий честный,
 * включая победителя.
 *
 * ────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ВЫПАДАЛО ОДНО И ТО ЖЕ
 *
 * Три причины, и первая перевешивала остальные.
 *
 * 1. Барабан набирался ИЗ ТЕКУЩЕЙ КОЛОДЫ — из тех самых карточек,
 *    что лежат перед человеком. Двадцать пять фильмов, из них десять
 *    в барабане: рулетка показывала то, что и так на экране. Теперь
 *    источник — весь загруженный каталог, сотни фильмов.
 *
 * 2. Отбор шёл по ОДНОЙ самой тяжёлой теме и брал строгий топ по её
 *    весу. Верхушка этого списка не меняется от запуска к запуску,
 *    так что «случайность» сводилась к перестановке одних и тех же
 *    фильмов. Теперь учитываются несколько любимых тем сразу.
 *
 * 3. Рулетка НЕ ПОМНИЛА, что уже показывала. Даже честный жребий
 *    из сотни повторяется чаще, чем кажется: человек замечает совпадение
 *    и делает вывод, что выбор сломан. Теперь недавно выпавшее
 *    исключается.
 * ────────────────────────────────────────────────────────────────
 */

import { topTags } from './tasteProfile.js';

/** Сколько фильмов участвует в прокрутке. */
export const REEL_SIZE = 10;

/**
 * Во сколько раз шире отбираем, прежде чем тянуть жребий.
 *
 * Ровно десять оставили бы рулетку без случайности: те же фильмы
 * каждый раз, просто в другом порядке. Шесть к одному — полоса
 * в шестьдесят фильмов: достаточно широкая, чтобы состав менялся,
 * и достаточно узкая, чтобы туда не попало случайное.
 */
const POOL_FACTOR = 6;

/**
 * Сколько любимых тем участвует в отборе.
 *
 * Одна тема — это одна и та же полка каждый раз. Три дают перекрёстку:
 * фильм с двумя любимыми темами обходит фильм с одной, и полоса
 * получается заметно разнообразнее при той же близости вкусу.
 */
const TAGS_IN_PLAY = 3;

/**
 * Сколько последних выпавших помним, чтобы не показывать снова.
 *
 * Сорок — примерно четыре прокрутки. Больше держать вредно: у человека
 * с узким вкусом память съела бы всю полосу, и рулетка начала бы
 * выдавать далёкое от него, лишь бы не повторяться.
 */
export const RECENT_MEMORY = 40;

/** Решения, после которых фильм в рулетке больше не участвует. */
const DECIDED = ['watched', 'dislike', 'later', 'favorite', 'like', 'match'];

/** Отбирает фильмы, про которые решение ещё не принято. */
export const rouletteCandidates = (pool, history = {}) =>
  (pool ?? []).filter((t) => t?.poster && !DECIDED.includes(history[t.id]));

/**
 * Честная перетасовка (Фишер — Йетс).
 *
 * `sort(() => random() - 0.5)` перемешивает неравномерно: компаратор
 * непоследователен, и распределение зависит от алгоритма сортировки.
 * Для рулетки, где случайность — весь смысл, это недопустимо.
 */
function shuffle(items, random) {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** Самая тяжёлая тема профиля. Null, пока человек ничего не насвайпал. */
export function favouriteTag(taste) {
  return topTags(taste, 1)[0]?.tag ?? null;
}

/**
 * Насколько фильм близок вкусу.
 *
 * Сумма по любимым темам, каждая со своим весом из профиля. Качество
 * добавлено малой долей и только как разделитель равных: если бы оно
 * весило всерьёз, полоса снова выродилась бы в «лучшее по рейтингу»,
 * то есть в тот же список каждый раз.
 */
function affinity(title, weights) {
  let score = 0;
  for (const { tag, weight } of weights) {
    score += (title.tags?.[tag] ?? 0) * weight;
  }

  /*
   * Ни одной любимой темы — фильм в полосу не попадает вовсе.
   *
   * Проверка обязана стоять ДО прибавки качества: иначе доля качества
   * даёт ненулевой балл каждому фильму каталога, и в полосу проходит
   * что угодно — достаточно быть хорошим. Рулетка тогда перестаёт
   * попадать во вкус, а именно это в ней и ценно.
   */
  if (score <= 0) return 0;

  return score + (title.quality ?? 0) * 0.05;
}

/**
 * Собирает барабан.
 *
 * @param {Array} candidates фильмы, про которые решение ещё не принято
 * @param {object} options
 * @param {number} options.size сколько фильмов крутится
 * @param {object} options.taste профиль вкуса — из него берутся любимые темы
 * @param {string[]} options.recent что уже выпадало недавно
 * @param {() => number} options.random источник случайности, подменяемый в тестах
 */
export function pickReel(candidates, {
  size = REEL_SIZE, taste = null, recent = [], random = Math.random,
} = {}) {
  if (!candidates?.length) return [];

  const weights = taste ? topTags(taste, TAGS_IN_PLAY) : [];

  /*
   * Полоса отбора: чем ближе вкусу, тем выше. Берём вшестеро больше
   * нужного и уже оттуда тянем жребий.
   */
  let band = candidates;
  if (weights.length) {
    const scored = candidates
      .map((title) => ({ title, score: affinity(title, weights) }))
      .filter((row) => row.score > 0)
      .sort((a, b) => b.score - a.score)
      .slice(0, size * POOL_FACTOR)
      .map((row) => row.title);

    // Любимых тем может не оказаться ни у кого из доступных — тогда
    // крутим что есть, это лучше пустого барабана.
    if (scored.length >= size) band = scored;
  }

  /*
   * Недавно выпавшее убираем — но не любой ценой.
   *
   * У человека с узким вкусом полоса может целиком состоять из уже
   * виденного. Показать далёкое от него, лишь бы не повторяться, —
   * худший исход: рулетка перестанет попадать. Поэтому если после
   * чистки не набирается барабан, возвращаем убранное.
   */
  const seen = new Set(recent);
  const fresh = band.filter((t) => !seen.has(t.id));
  const source = fresh.length >= size ? fresh : band;

  const reel = shuffle(source, random).slice(0, size);
  if (reel.length < 2) return reel;

  // Победитель — последний в ленте, и он тоже случаен: барабан уже
  // перетасован честно, так что достаточно ничего не переставлять.
  return reel;
}
