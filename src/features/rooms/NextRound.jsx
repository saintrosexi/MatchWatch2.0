import { useEffect, useState } from 'react';
import { Loader2, ICON } from '../../ui/icons.js';

/**
 * Ожидание следующей порции колоды.
 *
 * Пачка кончилась у всех, и дальше идёт пауза в несколько секунд: надо
 * пролистать каталог, сверить его с решениями каждого и пересчитать
 * подборку. Раньше здесь стояла одна строчка про то, что порция
 * собирается, — и пауза читалась как зависание, потому что ничего
 * не двигалось.
 *
 * Поэтому две вещи. Первая — честный срок: человек, который знает, что
 * ждать секунд десять, не жмёт назад на пятой. Вторая — факт о кино:
 * он занимает ровно ту паузу, которую всё равно надо переждать, и
 * заодно про кино, то есть к месту.
 *
 * Обещание намеренно с запасом. Сказать «пара секунд» и заставить ждать
 * десять — хуже, чем сказать «до десяти» и уложиться в пять.
 */

/**
 * Факты вынесены сюда и проверены поимённо.
 *
 * Байки про кино разлетаются быстрее правды, и подсунуть человеку
 * выдумку в приложении про кино — так себе идея. Здесь только то,
 * что подтверждено самими авторами фильмов.
 */
const FACTS = Object.freeze([
  'Звук светового меча Бен Бёртт собрал из гудения старого кинопроектора и помех, которые ловил микрофон возле телевизора.',
  'Акулу в «Челюстях» почти не показывают не ради саспенса: механическая модель постоянно ломалась, и Спилбергу пришлось снимать её отсутствие.',
  'Рёв Годзиллы получили, проведя кожаной перчаткой по струнам контрабаса и замедлив запись.',
  'Зелёные символы в заставке «Матрицы» — оцифрованные рецепты суши из поваренной книги: их набрал дизайнер Саймон Уайтли.',
  'Кот, которого Дон Корлеоне гладит в первой сцене «Крёстного отца», был бродячим — Копполе просто попался во дворе студии.',
  'Сцену с битой в «Сиянии» Кубрик снимал 127 дублей: рекорд для игрового кино с диалогом.',
  '«Ку» из «Кин-дза-дзы» Георгий Данелия придумал как единственное приличное слово чатланского языка — остальные значения оно набрало по ходу.',
  'В «Иван Васильевич меняет профессию» палаты снимали в павильоне «Мосфильма», а вид на Москву за окном — рисованный задник.',
  'Марлон Брандо не учил реплики к «Крёстному отцу»: текст лежал перед ним прямо в кадре, на подставках и на других актёрах.',
  '«Психо» стал первым американским фильмом, где на экране показали смыв унитаза, — и цензура возражала именно против этого, а не против сцены в душе.',
]);

/** Сколько держится один факт, прежде чем сменится. */
const ROTATE_MS = 7000;

export function NextRound() {
  /*
   * Случайный старт, а не первый по списку: иначе каждый вечер
   * начинается с одного и того же факта, и на третий раз он
   * раздражает сильнее самой паузы.
   */
  const [index, setIndex] = useState(() => Math.floor(Math.random() * FACTS.length));

  useEffect(() => {
    const timer = setInterval(() => {
      setIndex((n) => (n + 1) % FACTS.length);
    }, ROTATE_MS);
    return () => clearInterval(timer);
  }, []);

  return (
    <section className="next-round">
      <Loader2 size={ICON.lg} className="spin" />

      <div className="stack gap-1">
        <h2 className="next-round__title">Подбираем следующие фильмы</h2>
        <p className="faint" style={{ fontSize: 'var(--t-small)' }}>
          Порция общая, поэтому появится сразу у всех. Обычно это занимает
          до десяти секунд.
        </p>
      </div>

      {/*
        * Ключ по индексу нужен, чтобы факт не подменялся на месте,
        * а появлялся заново: подмена текста под глазами читается
        * как сбой, а не как смена карточки.
        */}
      <p className="next-round__fact" key={index}>{FACTS[index]}</p>
    </section>
  );
}
