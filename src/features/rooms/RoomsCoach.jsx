import { LogIn, Plus } from '../../ui/icons.js';
import { Coach, coachSeen } from '../../ui/Coach.jsx';

const SEEN_KEY = 'coach:rooms';

/**
 * Обучение на экране «Вместе». Два шага, и больше не нужно.
 *
 * Здесь ровно два действия — создать комнату или войти в чужую, — и они
 * оба на виду. Объяснять больше значит объяснять то, что человек и так
 * читает с экрана: подсказка поверх очевидного раздражает и обесценивает
 * следующую.
 *
 * Смысл шагов не в том, ЧТО нажать, а в том, чего человек не видит:
 * что код нужен второму, а не ему самому, и что свайпать они будут
 * каждый со своего телефона, а не по очереди с одного.
 */
const STEPS = [
  {
    key: 'create',
    target: '[data-coach="room-create"]',
    title: 'Создайте комнату',
    text: 'Комната получит код из четырёх цифр. Код — для второго: '
      + 'вы отправляете его в чат, а сами уже внутри. Можно позвать '
      + 'и ссылкой, тогда код вводить не придётся никому.',
    rows: [
      { icon: Plus, tone: 'like', label: 'создаёт один — заходят двое' },
    ],
    place: 'below',
  },
  {
    key: 'join',
    target: '[data-coach="room-join"]',
    title: 'Или войдите по коду',
    text: 'Если комнату создал друг — введите его код здесь. '
      + 'Дальше вы листаете одну колоду, но каждый со своего телефона '
      + 'и не видя чужих решений: мэтч случается, только когда «нравится» '
      + 'сказали оба.',
    rows: [
      { icon: LogIn, tone: 'info', label: 'четыре цифры от того, кто создал' },
    ],
    place: 'above',
  },
];

export function RoomsCoach({ active = false, onDone }) {
  return (
    <Coach steps={STEPS} seenKey={SEEN_KEY} area="rooms" active={active} onDone={onDone} />
  );
}

/** Видел ли человек подсказки экрана «Вместе». */
export const roomsCoachSeen = () => coachSeen(SEEN_KEY);
