-- MatchWatch: снимаем жёсткий потолок визитки в шесть фильмов.
--
-- Проверка `profiles_pinned_limit` была заведена мимо файлов миграций
-- и держала `array_length(pinned_ids, 1) <= 6` намертво. Рядом с ней
-- жила новая, `profiles_pinned_within_limit`, которая смотрит на
-- `pin_limit` конкретного человека: шесть по умолчанию, двенадцать
-- с подпиской.
--
-- Пока обе стояли рядом, побеждала старая: сохранить седьмой фильм
-- не мог никто, и обещанные подписчику двенадцать не работали ни разу.
-- Наружу это выходило ошибкой базы прямо в лицо пользователю.
alter table public.profiles drop constraint if exists profiles_pinned_limit;
