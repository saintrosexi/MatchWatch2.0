/** Доступен ли акцент. Незнакомые ключи считаем бесплатными — не запрещаем лишнего. */
export function accentAllowed(key, { premium = false, config = PREMIUM_CONFIG } = {}) {
  if (config.grantAllUsers || premium) return true;
  return !config.profile.accents.premium.includes(key);
}

/** Доступна ли фактура карточки. */
export function frameAllowed(key, { premium = false, config = PREMIUM_CONFIG } = {}) {
  if (config.grantAllUsers || premium) return true;
  return !config.profile.frames.premium.includes(key);
}

/** Доступна ли настройка витрины. */
export function showcaseAllowed({ premium = false, config = PREMIUM_CONFIG } = {}) {
  if (config.profile.showcase !== 'premium') return true;
  return Boolean(config.grantAllUsers || premium);
}

/** Сколько фильмов можно закрепить прямо сейчас. */
export function pinLimitFor({ premium = false, config = PREMIUM_CONFIG } = {}) {
  const { free, premium: paid } = config.profile.pinLimit;
  return (config.grantAllUsers || premium) ? paid : free;
}

/** Активна ли подписка. Истина — дата, а не поле статуса: оно может отстать. */
export function isPremiumActive(subscription, { now = Date.now(), config = PREMIUM_CONFIG } = {}) {
  if (config.grantAllUsers) return true;
  if (!subscription?.expires_at) return false;
  if (subscription.status === 'cancelled') return false;
  return new Date(subscription.expires_at).getTime() > now;
}

/** Сколько дней осталось. Отрицательные не отдаём — их неудобно показывать. */
export function premiumDaysLeft(subscription, { now = Date.now() } = {}) {
  if (!subscription?.expires_at) return 0;
  const ms = new Date(subscription.expires_at).getTime() - now;
  return Math.max(0, Math.ceil(ms / 86400000));
}

/**
 * Применяется ли лимит бесплатного тарифа.
 *
 * Один вход для всех проверок: пока премиум у всех либо лимит не задан,
 * ответ «нет». Так вызывающий код не обязан знать про `grantAllUsers`
 * и не разъедется с конфигом, когда флаг снимут.
 */
export function freeLimitFor(key, { premium = false, config = PREMIUM_CONFIG } = {}) {
  if (config.grantAllUsers || premium) return null;
  return config.freeLimits?.[key] ?? null;
}
