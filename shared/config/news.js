/** Запись для баннера — первая помеченная. Ноль записей это тоже норма. */
export const bannerNews = () => NEWS.find((item) => item.banner) ?? null;

/** Все идентификаторы: ими помечается «прочитано». */
export const newsIds = () => NEWS.map((item) => item.id);

/**
 * Записи, сгруппированные по выпуску, в порядке файла.
 *
 * Нужно странице: без группировки двенадцать статей подряд читаются
 * как поток, из которого не видно, что вышло вместе. Порядок групп
 * и порядок внутри них задаёт файл, а не сортировка.
 */
export function newsByRelease() {
  const groups = [];

  for (const item of NEWS) {
    const release = item.release ?? null;
    const last = groups[groups.length - 1];

    if (last && last.release === release) last.items.push(item);
    else groups.push({ release, items: [item] });
  }

  return groups;
}
