/**
 * MatchWatch — дневник разработки.
 *
 * Один список на две поверхности: баннер, который показывается один раз
 * при следующем заходе, и страница дневника. Держать их раздельно нельзя —
 * тогда баннер обещал бы одно, а страница рассказывала бы другое.
 *
 * ────────────────────────────────────────────────────────────────
 * ГДЕ ЧТО ПРАВИТЬ
 *
 *   Текст объявления и статей .......... этот файл, массив `NEWS`
 *   Цена в звёздах и рублях ............ shared/config/premium.js,
 *                                        поле `price`
 *   Список возможностей подписки ....... shared/config/premium.js,
 *                                        поле `benefits` (он же
 *                                        подставляется сюда по `listFrom`)
 *
 * Больше нигде эти строки не дублируются: витрина, объявление
 * и страница дневника читают их отсюда.
 * ────────────────────────────────────────────────────────────────
 * КАК ДОБАВИТЬ ЗАПИСЬ
 *
 * Дописать объект В НАЧАЛО массива. Порядок в файле и есть порядок
 * на странице: сортировки по дате нет намеренно, иначе опечатка
 * в дате молча перемешала бы историю продукта.
 *
 * `id` менять нельзя никогда. По нему запоминается, что человек уже
 * видел эту новость; смена идентификатора покажет её всем повторно.
 *
 * `release` собирает записи в выпуск. Страница группирует их по этому
 * полю и рисует заголовок выпуска: так видно, что вышло вместе,
 * а не просто в один день.
 * ────────────────────────────────────────────────────────────────
 */

